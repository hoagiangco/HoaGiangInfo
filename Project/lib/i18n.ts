export function getTranslation(lang: Language, key: string, params?: Record<string, string | number>): string {
  let translation = translations[lang]?.[key] || translations['vi'][key] || key;
  
  // Replace placeholders like {current} and {total}
  if (params) {
    Object.entries(params).forEach(([paramKey, paramValue]) => {
      translation = translation.replace(`{${paramKey}}`, String(paramValue));
    });
  }
  
  return translation;
}

export function detectLanguage(): Language {
  if (typeof window === 'undefined') return 'vi';
  
  const browserLang = navigator.language.split('-')[0];
  if (languages.includes(browserLang as Language)) {
    return browserLang as Language;
  }
  return 'vi';
}


